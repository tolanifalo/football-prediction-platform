-- ===========================================================================
-- 1. AS-OF WRAPPER (§11.1, consumed here - P1-01 owns neither the mechanism
--    nor its design)
-- ===========================================================================
-- The SIXTH wrapper. It DELEGATES to fn_visible_at and never restates the
-- predicate; the P0-06 catalog assertion must still find exactly one object
-- defining the visibility comparison, so restating it here fails CI by design.
--
-- LANGUAGE sql is load-bearing, as in 0008, 0010, 0013 and 0015: SQL functions
-- inline, so the wrapper plans identically to a hand-written predicate and
-- preserves the index scan. PL/pgSQL is an optimisation barrier.
--
-- THIS WRAPPER BOUNDS TRANSACTION TIME ONLY. It answers "which predictions had
-- we PRODUCED by T". It says nothing about what those predictions were
-- entitled to know - that is data_cutoff, a separate column on a separate
-- axis, and a reproducibility read must filter it itself:
--
--   SELECT * FROM predictions_as_of(:T)          -- what we had GENERATED by T
--    WHERE fixture_id = :f
--      AND data_cutoff = :c                      -- what the model KNEW
--      AND model_version = :v AND profile = :p;  -- which model
--
-- Omitting data_cutoff returns every generation for the fixture, which is the
-- correct answer to a different question and the wrong one here.
CREATE FUNCTION predictions_as_of(cutoff timestamptz)
RETURNS SETOF predictions
LANGUAGE sql STABLE AS $$
	SELECT * FROM predictions WHERE fn_visible_at(known_at, superseded_at, cutoff)
$$;
--> statement-breakpoint

-- ===========================================================================
-- 2. GRANTS
-- ===========================================================================
-- Predictions are APPEND-ONLY, like every other revisioned artifact (§6 rule
-- 3). engine_rw may insert a generation and close one; it may not rewrite a
-- probability, because a silently edited prediction is indistinguishable from
-- one that was always that value, and the whole point of storing data_cutoff
-- is that a historical prediction stays exactly as it was made.
GRANT SELECT, INSERT ON "predictions" TO "engine_rw";--> statement-breakpoint
GRANT UPDATE ("superseded_at") ON "predictions" TO "engine_rw";
--> statement-breakpoint

-- The web read path. app_rw READS predictions and never writes one: rule 9
